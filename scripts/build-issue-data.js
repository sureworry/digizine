#!/usr/bin/env node
/**
 * Build issue-data.js from actual folders in assets/issues.
 * Auto-discovers all zine folders; no fixed page counts.
 * Run from project root: node scripts/build-issue-data.js
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const ISSUES_DIR = path.join(ROOT, 'assets', 'issues');
const OUT_PATH = path.join(ROOT, 'issue-data.js');

const IMAGE_EXT = /\.(png|jpe?g|webp)$/i;

function folderToSlug(folderName) {
  return folderName.trim().replace(/\s+/g, '-').toLowerCase();
}

function listDirs(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort();
}

function listImages(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir).filter((name) => IMAGE_EXT.test(name));
}

function isCoverLike(name) {
  return /cover/i.test(name);
}

function pageNumber(name) {
  const m = name.match(/page[\s\-_]?(\d+)/i);
  return m ? parseInt(m[1], 10) : null;
}

function sortForReading(files) {
  return [...files].sort((a, b) => {
    const aCover = isCoverLike(a);
    const bCover = isCoverLike(b);
    if (aCover && !bCover) return -1;
    if (!aCover && bCover) return 1;
    if (aCover && bCover) return a.localeCompare(b);
    const na = pageNumber(a);
    const nb = pageNumber(b);
    if (na != null && nb != null) return na - nb;
    if (na != null) return -1;
    if (nb != null) return 1;
    return a.localeCompare(b);
  });
}

function buildIssue(folderName) {
  const folderPath = path.join(ISSUES_DIR, folderName);
  if (!fs.existsSync(folderPath) || !fs.statSync(folderPath).isDirectory()) {
    return null;
  }

  const files = listImages(folderPath);
  if (files.length === 0) return null;

  const ordered = sortForReading(files);
  const coverInFolder = ordered.find(isCoverLike);

  const pages = [];
  for (const file of ordered) {
    if (isCoverLike(file) && coverInFolder === file) {
      pages.push({ type: 'cover' });
      continue;
    }
    const src = `assets/issues/${folderName}/${file}`.replace(/\\/g, '/');
    const num = pageNumber(file);
    const label = num != null ? `page ${num}` : file.replace(/\.[^.]+$/, '');
    pages.push({ type: 'image', src, label });
  }

  const coverSrc = coverInFolder
    ? `assets/issues/${folderName}/${coverInFolder}`.replace(/\\/g, '/')
    : null;

  const issue = {
    title: folderName,
    pages
  };
  if (coverSrc) issue.cover = coverSrc;

  return issue;
}

function main() {
  const folders = listDirs(ISSUES_DIR);
  const issues = {};

  for (const folderName of folders) {
    const issue = buildIssue(folderName);
    if (!issue) continue;
    const slug = folderToSlug(folderName);
    issues[slug] = issue;
  }

  const out = `// Generated by scripts/build-issue-data.js from assets/issues. Do not edit by hand.
// Run: node scripts/build-issue-data.js

var ISSUE_DATA = ${JSON.stringify(issues, null, 2)};

function getIssueBySlug(slug) {
  return ISSUE_DATA[slug] || null;
}
`;

  fs.writeFileSync(OUT_PATH, out, 'utf8');
  console.log('Wrote', OUT_PATH, '—', Object.keys(issues).length, 'issues');
}

main();
